"""Draws the face's tick ring as images (the ARC widget renders tiny arcs as fuzzy blobs):

- assets/default/ring_dim.png: all sixty ticks, dim, full screen (480 x 480, transparent);
- assets/default/tick/tNN.png: each tick lit, cropped to its own box;
- watchface/ticks.js: where each lit tick goes.

Drawn at 4x and scaled down, so the ticks are anti-aliased. Run from zepp-face/:
    python -I tools/make_ticks.py
"""
import math
import os

from PIL import Image, ImageDraw

SIZE = 480
SS = 4
OUTER = 236
MINOR, MAJOR = 12, 22
WIDTH_MINOR, WIDTH_MAJOR = 3.2, 5.0
DIM = (60, 66, 60, 255)
LIT = (166, 227, 110, 255)

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
assets = os.path.join(root, "assets", "default")
os.makedirs(os.path.join(assets, "tick"), exist_ok=True)


def tick_image(i, color, full):
    big = Image.new("RGBA", (SIZE * SS, SIZE * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    ticks = range(60) if full else [i]
    for k in ticks:
        major = k % 5 == 0
        length = MAJOR if major else MINOR
        width = WIDTH_MAJOR if major else WIDTH_MINOR
        a = math.radians(-90 + k * 6)
        c = SIZE / 2 * SS
        r1 = (OUTER - width / 2) * SS
        r0 = (OUTER - length + width / 2) * SS
        p0 = (c + r0 * math.cos(a), c + r0 * math.sin(a))
        p1 = (c + r1 * math.cos(a), c + r1 * math.sin(a))
        w = int(round(width * SS))
        d.line([p0, p1], fill=color, width=w)
        # Round ends.
        for p in (p0, p1):
            d.ellipse([p[0] - w / 2, p[1] - w / 2, p[0] + w / 2, p[1] + w / 2], fill=color)
    return big.resize((SIZE, SIZE), Image.LANCZOS)


tick_image(0, DIM, True).save(os.path.join(assets, "ring_dim.png"))

boxes = []
for i in range(60):
    im = tick_image(i, LIT, False)
    box = im.getbbox()
    im.crop(box).save(os.path.join(assets, "tick", "t%02d.png" % i))
    boxes.append(box[:2])

with open(os.path.join(root, "watchface", "ticks.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_ticks.py: top-left corner of each lit tick image, by second.\n")
    f.write("export const TICKS = [\n")
    for i in range(0, 60, 6):
        f.write("  " + ", ".join("[%d, %d]" % b for b in boxes[i:i + 6]) + ",\n")
    f.write("]\n")
print("ok", len(boxes))
